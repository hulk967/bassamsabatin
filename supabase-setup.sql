-- شغّل هذا الملف داخل Supabase SQL Editor.
-- قبل التشغيل: أنشئ مستخدم الأدمن من Authentication > Users > Add user.

create table if not exists public.site_settings (
  id int primary key default 1,
  key text not null default 'main' unique,
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz default now()
);

alter table public.site_settings add column if not exists key text not null default 'main';
create unique index if not exists site_settings_key_unique on public.site_settings(key);

-- كل مستخدم موجود وقت تشغيل الملف يُعتمد كأدمن. المستخدمون الجدد لا يحصلون على الصلاحية تلقائياً.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz default now()
);
alter table public.admin_users enable row level security;
insert into public.admin_users (user_id, email)
select id, email from auth.users where email is not null
on conflict (user_id) do update set email = excluded.email;

create or replace function public.is_site_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.admin_users where user_id = auth.uid()) $$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to anon, authenticated;

create table if not exists public.projects (
