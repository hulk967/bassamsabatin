-- Storage bucket للصور والفيديوهات التي ترفعها من لوحة الأدمن
insert into storage.buckets (id, name, public)
values ('site-assets', 'site-assets', true)
on conflict (id) do update set public = true;

drop policy if exists "public read site-assets" on storage.objects;
drop policy if exists "admin upload site-assets" on storage.objects;
drop policy if exists "admin update site-assets" on storage.objects;
drop policy if exists "admin delete site-assets" on storage.objects;
create policy "public read site-assets" on storage.objects for select using (bucket_id = 'site-assets');
create policy "admin upload site-assets" on storage.objects for insert with check (bucket_id = 'site-assets' and public.is_site_admin());
create policy "admin update site-assets" on storage.objects for update using (bucket_id = 'site-assets' and public.is_site_admin()) with check (bucket_id = 'site-assets' and public.is_site_admin());
create policy "admin delete site-assets" on storage.objects for delete using (bucket_id = 'site-assets' and public.is_site_admin());

